import 'package:flutter_riverpod/flutter_riverpod.dart';
import 'package:universal_html/html.dart' as html;

////////////////////////////////////////////////////////////
/// NOTIFIER
////////////////////////////////////////////////////////////

class CurrentJobNotifier extends Notifier<String?> {
  @override
  String? build() {
    ////////////////////////////////////////////////////////////
    /// LOAD FROM LOCAL STORAGE
    ////////////////////////////////////////////////////////////
    try {
      return html.window.localStorage['resume_job_id'];
    } catch (e) {
      return null;
    }
  }

  ////////////////////////////////////////////////////////////
  /// SET JOB
  ////////////////////////////////////////////////////////////

  void setJob(String jobId) {
    state = jobId;

    try {
      html.window.localStorage['resume_job_id'] = jobId;
    } catch (_) {}
  }

  ////////////////////////////////////////////////////////////
  /// CLEAR JOB
  ////////////////////////////////////////////////////////////

  void clear() {
    state = null;

    try {
      html.window.localStorage.remove('resume_job_id');
    } catch (_) {}
  }
}

////////////////////////////////////////////////////////////
/// PROVIDER
////////////////////////////////////////////////////////////

final currentJobProvider = NotifierProvider<CurrentJobNotifier, String?>(
  CurrentJobNotifier.new,
);
